// TestGenerateCheck is the drift gate: green against what this binary wrote,
// red on a specification that was changed without regenerating, on a generated
// file edited by hand, and on a file no specification accounts for.
func TestGenerateCheck(t *testing.T) {
	out := generated(t)
	args := []string{"generate", "-f", "testdata/detectors", "-o", out, "--check"}

	var stdout, stderr bytes.Buffer
	if got := run(t.Context(), args, &stdout, &stderr); got != exitOK {
		t.Fatalf("exit code = %d, want %d\nstderr: %s", got, exitOK, stderr.String())
	}

	t.Run("a generated file edited by hand", func(t *testing.T) {
		path := filepath.Join(generated(t), "checkout.yaml")
		data, err := os.ReadFile(path)
		if err != nil {
			t.Fatalf("reading %s: %v", path, err)
		}
		edited := strings.Replace(string(data), "interval: 1m", "interval: 5m", 1)
		if edited == string(data) {
			t.Fatal("the fixture no longer contains the line this case edits")
		}
		if err := os.WriteFile(path, []byte(edited), 0o644); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		var stdout, stderr bytes.Buffer
		args := []string{"generate", "-f", "testdata/detectors", "-o", filepath.Dir(path), "--check"}
		if got := run(t.Context(), args, &stdout, &stderr); got != exitFinding {
			t.Fatalf("exit code = %d, want %d", got, exitFinding)
		}
		if !strings.Contains(stderr.String(), "checkout.yaml") {
			t.Errorf("stderr = %q, want it to name the file that drifted", stderr.String())
		}
	})

	t.Run("a missing file", func(t *testing.T) {
		dir := generated(t)
		if err := os.Remove(filepath.Join(dir, "checkout.yaml")); err != nil {
			t.Fatalf("removing: %v", err)
		}

		var stdout, stderr bytes.Buffer
		args := []string{"generate", "-f", "testdata/detectors", "-o", dir, "--check"}
		if got := run(t.Context(), args, &stdout, &stderr); got != exitFinding {
			t.Fatalf("exit code = %d, want %d", got, exitFinding)
		}
	})

	t.Run("a file no specification accounts for", func(t *testing.T) {
		dir := generated(t)
		path := filepath.Join(dir, "deleted-detector.yaml")
		if err := os.WriteFile(path, []byte("groups: []\n"), 0o644); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}

		var stdout, stderr bytes.Buffer
		args := []string{"generate", "-f", "testdata/detectors", "-o", dir, "--check"}
		if got := run(t.Context(), args, &stdout, &stderr); got != exitFinding {
			t.Fatalf("exit code = %d, want %d", got, exitFinding)
		}
		if !strings.Contains(stderr.String(), "deleted-detector.yaml") {
			t.Errorf("stderr = %q, want it to name the file nothing produced", stderr.String())
		}
	})

	t.Run("check writes nothing", func(t *testing.T) {
		dir := t.TempDir()

		var stdout, stderr bytes.Buffer
		args := []string{"generate", "-f", "testdata/detectors", "-o", dir, "--check"}
		if got := run(t.Context(), args, &stdout, &stderr); got != exitFinding {
			t.Fatalf("exit code = %d, want %d", got, exitFinding)
		}
		entries, err := os.ReadDir(dir)
		if err != nil {
			t.Fatalf("reading %s: %v", dir, err)
		}
		if len(entries) != 0 {
			t.Errorf("--check wrote %d files, want none", len(entries))
		}
	})
}

// TestGenerateFlags covers every way the command refuses to run.
func TestGenerateFlags(t *testing.T) {
	tests := []struct {
		name     string
		args     []string
		inStderr string
	}{
		{
			name:     "no flags prints usage",
			args:     nil,
			inStderr: "usage: feno generate",
		},
		{
			name:     "a path with no output directory prints usage",
			args:     []string{"-f", "testdata/detectors"},
			inStderr: "usage: feno generate",
		},
		{
			name:     "a target nobody implements",
			args:     []string{"-f", "testdata/detectors", "-o", "out", "-t", "clickhouse"},
			inStderr: `-t "clickhouse"`,
		},
		{
			name:     "a path that is not there",
			args:     []string{"-f", "testdata/nope.yaml", "-o", "out"},
			inStderr: "no such file or directory",
		},
		{
			name: "a probed server and the offline override together",
			args: []string{"-f", "testdata/detectors", "-o", "out",
				"--url", "http://localhost:9090", "--experimental-functions"},
			inStderr: "--url and --experimental-functions",
		},
		{
			name:     "specifications with no detector in them",
			args:     []string{"-f", "testdata/datasource.yaml", "-o", "out"},
			inStderr: "no detector to generate from",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer

			got := run(t.Context(), append([]string{"generate"}, tt.args...), &stdout, &stderr)
			if got != exitUsage {
				t.Errorf("exit code = %d, want %d\nstderr: %s", got, exitUsage, stderr.String())
			}
			if !strings.Contains(stderr.String(), tt.inStderr) {
				t.Errorf("stderr = %q, want it to contain %q", stderr.String(), tt.inStderr)
			}
			if stdout.Len() != 0 {
				t.Errorf("stdout = %q, want nothing", stdout.String())
			}
		})
	}
}

// probed starts a server that answers the capability probe with body and
// status, and returns its URL and the headers it was asked with.
func probed(t *testing.T, status int, body string) (string, *[]http.Header) {
	t.Helper()

	var headers []http.Header
	srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		headers = append(headers, r.Header.Clone())
		if r.URL.Path != "/api/v1/query" {
			t.Errorf("probe asked %q, want %q", r.URL.Path, "/api/v1/query")
		}
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(status)
		if _, err := io.WriteString(w, body); err != nil {
			t.Errorf("writing response: %v", err)
		}
	}))
	t.Cleanup(srv.Close)

	return srv.URL, &headers
}

const (
	probeAnswered = `{"status":"success","data":{"resultType":"vector","result":[]}}`
	probeUnknown  = `{"status":"error","errorType":"bad_data","error":"invalid parameter \"query\": 1:1: parse error: unknown function with name \"mad_over_time\""}`
)

// TestGenerateProbesTarget is Part 11's capability model end to end: the same
// specification compiles to the median absolute deviation against a server
// that has the function and to the interquartile range against one that does
// not, and the command says which.
func TestGenerateProbesTarget(t *testing.T) {
	tests := []struct {
		name     string
		status   int
		body     string
		inRules  string
		inStderr string
	}{
		{
			name:     "a server with the function enabled",
			status:   http.StatusOK,
			body:     probeAnswered,
			inRules:  "mad_over_time",
			inStderr: "mad_over_time available, emitting median absolute deviation",
		},
		{
			name:     "a server without it",
			status:   http.StatusBadRequest,
			body:     probeUnknown,
			inRules:  "quantile_over_time(0.75,",
			inStderr: "mad_over_time unavailable, emitting interquartile range",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			url, _ := probed(t, tt.status, tt.body)
			out := t.TempDir()

			var stdout, stderr bytes.Buffer
			args := []string{"generate", "-f", "testdata/detectors", "-o", out, "--url", url}
			if got := run(t.Context(), args, &stdout, &stderr); got != exitOK {
				t.Fatalf("exit code = %d, want %d\nstderr: %s", got, exitOK, stderr.String())
			}

			data, err := os.ReadFile(filepath.Join(out, "api-latency.yaml"))
			if err != nil {
				t.Fatalf("reading: %v", err)
			}
			if !strings.Contains(string(data), tt.inRules) {
				t.Errorf("api-latency.yaml does not contain %q:\n%s", tt.inRules, data)
			}
			if !strings.Contains(stderr.String(), url) {
				t.Errorf("stderr = %q, want it to name the server probed", stderr.String())
			}
			if !strings.Contains(stderr.String(), tt.inStderr) {
				t.Errorf("stderr = %q, want it to contain %q", stderr.String(), tt.inStderr)
			}
		})
	}
}

// TestGenerateProbeSendsHeaders covers the multi-tenant target: the probe is a
// query like any other and Mimir will not answer it without X-Scope-OrgID.
func TestGenerateProbeSendsHeaders(t *testing.T) {
	url, headers := probed(t, http.StatusOK, probeAnswered)

	var stdout, stderr bytes.Buffer
	args := []string{"generate", "-f", "testdata/detectors", "-o", t.TempDir(),
		"--url", url, "--header", "X-Scope-OrgID=team-checkout"}
	if got := run(t.Context(), args, &stdout, &stderr); got != exitOK {
		t.Fatalf("exit code = %d, want %d\nstderr: %s", got, exitOK, stderr.String())
	}

	if len(*headers) != 1 {
		t.Fatalf("the probe made %d requests, want 1", len(*headers))
	}
	if got := (*headers)[0].Get("X-Scope-OrgID"); got != "team-checkout" {
		t.Errorf("X-Scope-OrgID = %q, want %q", got, "team-checkout")
	}
}

// TestGenerateProbeFailureWritesNothing is why the probe returns an error: a
// band that changed shape because something in the path was broken has to be
// loud, not a silent fallback to the other form.
func TestGenerateProbeFailureWritesNothing(t *testing.T) {
	url, _ := probed(t, http.StatusServiceUnavailable, "upstream connect error")
	out := t.TempDir()

	var stdout, stderr bytes.Buffer
	args := []string{"generate", "-f", "testdata/detectors", "-o", out, "--url", url}
	if got := run(t.Context(), args, &stdout, &stderr); got == exitOK {
		t.Fatalf("exit code = %d, want a failure\nstderr: %s", got, stderr.String())
	}
	if !strings.Contains(stderr.String(), "mad_over_time") {
		t.Errorf("stderr = %q, want it to say what failed", stderr.String())
	}

	entries, err := os.ReadDir(out)
	if err != nil {
		t.Fatalf("reading %s: %v", out, err)
	}
	if len(entries) != 0 {
		t.Errorf("a failed probe wrote %d files, want none", len(entries))
	}
}

// TestGenerateOutputFromConfig is the output directory as a fact about the
// repository rather than a flag every invocation has to repeat. The target in
// feno.yaml is found by walking up from the specifications, which is the same
// walk the noise budget takes.
func TestGenerateOutputFromConfig(t *testing.T) {
	root := t.TempDir()
	specs := filepath.Join(root, "detectors")
	if err := os.MkdirAll(specs, 0o750); err != nil {
		t.Fatal(err)
	}
	detector, err := os.ReadFile("testdata/detectors/checkout.yaml")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(specs, "checkout.yaml"), detector, 0o600); err != nil {
		t.Fatal(err)
	}
	settings := "targets:\n  - engine: prometheus\n    output: rules/anomaly\n"
	if err := os.WriteFile(filepath.Join(root, config.Filename), []byte(settings), 0o600); err != nil {
		t.Fatal(err)
	}

	// -f names the tree the target is declared in, and internal/spec walks
	// it, so the specifications may sit a directory below the file.
	var stdout, stderr bytes.Buffer
	if got := run(t.Context(), []string{"generate", "-f", root}, &stdout, &stderr); got != exitOK {
		t.Fatalf("exit code = %d, want %d\nstderr: %s", got, exitOK, stderr.String())
	}

	// The output path is relative to the file that declared it, not to the
	// working directory, because the file describes a repository layout and a
	// command is run from wherever somebody happens to be.
	written := filepath.Join(root, "rules", "anomaly", "checkout.yaml")
	if _, err := os.Stat(written); err != nil {
		t.Fatalf("expected a rule file at %s: %v", written, err)
	}
	// Writing somewhere a reader cannot predict is worse than refusing, so
	// the directory it chose is said out loud.
	if !strings.Contains(stdout.String()+stderr.String(), filepath.Join(root, "rules", "anomaly")) {
		t.Errorf("output = %q, want it to name the directory it wrote to", stdout.String()+stderr.String())
	}
}

// TestGenerateOutputFlagBeatsConfig keeps the flag winning. The budget is the
// thing a flag may not loosen; an output directory is not a limit.
func TestGenerateOutputFlagBeatsConfig(t *testing.T) {
	root := t.TempDir()
	settings := "targets:\n  - engine: prometheus\n    output: rules/anomaly\n"
	if err := os.WriteFile(filepath.Join(root, config.Filename), []byte(settings), 0o600); err != nil {
		t.Fatal(err)
	}
	out := t.TempDir()

	var stdout, stderr bytes.Buffer
	args := []string{"generate", "-f", "testdata/detectors", "-o", out, "-config", filepath.Join(root, config.Filename)}
	if got := run(t.Context(), args, &stdout, &stderr); got != exitOK {
		t.Fatalf("exit code = %d, want %d\nstderr: %s", got, exitOK, stderr.String())
	}
	if _, err := os.Stat(filepath.Join(out, "checkout.yaml")); err != nil {
		t.Fatalf("expected a rule file at %s: %v", out, err)
	}
	if _, err := os.Stat(filepath.Join(root, "rules", "anomaly")); err == nil {
		t.Error("the config output directory was written to as well as the flag's")
	}
}

